#!/bin/bash
# Regression test for the -X (CORE region-exploration refinement) option of scripts/blant-clusters.sh.
# Uses saved BLANT samples for networks/CElegans.el (k=4, seed 1) so no sampling is needed for the main tests.
die() { echo "$@" >&2; exit 1
}

echo 'Testing blant-clusters -X (CORE refinement)'

TEST_DIR=`pwd`/regression-tests/blant-clusters-core
[ -d "$TEST_DIR" ] || die "should be run from top-level directory of the BLANT repo"
TMP=`mktemp -d ${TMPDIR:-/tmp}/blant-clusters-core.XXXXXX` || die "cannot make temp dir"
trap "/bin/rm -rf $TMP" 0

exitCode=0
fail() { echo "FAILED: $@" >&2; exitCode=1; }

# run_net NETFILE SAMPLEDIR OPTS ED: cluster lines on stdout; fails if the script fails or any stage reports an
# assertion failure (the script's own exit status does not cover the awk stages inside its pipelines)
run_net() { ./scripts/blant-clusters.sh $3 -T $TMP -D $2 -r 1 ./blant 4 $4 $1 2>$TMP/stderr || return 1
    if grep -q "ASSERTION failure" $TMP/stderr; then return 1; fi; }
# run_clusters OPTS ED: the saved CElegans samples
run_clusters() { run_net networks/CElegans.el $TEST_DIR/samples "$1" $2; }
run_clusters_stderr() { run_clusters "$1" $2 >/dev/null; cat $TMP/stderr; }
# run_on NAME OPTS ED: a network generated by this test, $TMP/NAME.el (or .elw), samples in $TMP/NAME/
run_on() { local net=$TMP/$1.el; [ -f $net ] || net=$TMP/$1.elw; run_net $net $TMP/$1 "$2" $3; }
# make_samples NAME [blant options]: sample a generated network with the same command blant-clusters uses
make_samples() { local name=$1; shift; local net=$TMP/$name.el; [ -f $net ] || net=$TMP/$name.elw
    mkdir -p $TMP/$name && ./blant -p0.9L -q "$@" -r 1 -k4 -sEBE -mcg $net > $TMP/$name/blant4.out 2>/dev/null; }
# stats FILE: "count biggest top5sum minDensity" for lines "N nodes, e/m edges, D% density ..."
stats() { sort -k1,1nr "$@" | awk '{split($3,a,"/"); d=a[1]/a[2]; if(NR==1||d<minD)minD=d; if(NR==1)big=$1; if(NR<=5)top+=$1}
	END{printf "%d %d %d %.6f\n", NR, big, top, (NR?minD:1)}'; }

# test_X0_identical: -X 0 and -X0 reproduce the pre-change output byte for byte
for ed in 0.5 0.125; do
    run_clusters "-X 0" $ed | cmp -s - $TEST_DIR/golden-X0-ed$ed.out || fail "-X 0 differs from golden at ED $ed"
    run_clusters "-X0"  $ed | cmp -s - $TEST_DIR/golden-X0-ed$ed.out || fail "-X0 differs from golden at ED $ed"
done

# test_density_floor: no cluster below ED with refinement on
# test_bigger: the biggest cluster is larger than without refinement. (Only the biggest is compared: every community
# can only gain nodes, which check mode verifies per community below, but larger communities overlap more, so on a
# small network fewer of them survive the overlap filter and rank-by-rank sizes are not comparable.)
# test_repeatable: same seed twice gives identical output
for ed in 0.5 0.125; do
    run_clusters "" $ed > $TMP/new-$ed.out || fail "ED $ed: script exited non-zero"
    read c big top minD <<< "`stats $TMP/new-$ed.out`"
    read gc gbig gtop gminD <<< "`stats $TEST_DIR/golden-X0-ed$ed.out`"
    awk "BEGIN{exit !($minD >= $ed)}"        || fail "cluster below ED $ed: $minD"
    [ $c -ge 1 ] && [ $big -gt $gbig ]       || fail "ED $ed: $c clusters, biggest $big; without refinement $gc clusters, biggest $gbig"
    run_clusters "" $ed | cmp -s - $TMP/new-$ed.out || fail "ED $ed: not repeatable with -r 1"
done

# ---- generated networks
# twocore: CORE's motivating example. Core A is a 12-clique, core B an 8-clique, joined by only two bridge edges
# (a1-b1, a2-b2). Each core has satellites with 2 edges into it. At ED 0.5, growing A one node at a time gets stuck
# on satellites at 18 nodes (78/153); A plus B together is 20 nodes (96/190), reachable from A only by adding a
# group of B nodes at once, which is what region exploration does.
gen_twocore() { awk -v pre="$1" 'BEGIN{
    for(i=1;i<=12;i++) for(j=i+1;j<=12;j++) print pre"a"i, pre"a"j;
    for(i=1;i<=8;i++) { for(j=i+1;j<=8;j++) print pre"b"i, pre"b"j; if(i<=2) print pre"b"i, pre"a"i; }
    for(i=1;i<=12;i++) { print pre"s"i, pre"a"i; print pre"s"i, pre"a"(i%12+1); }
    for(i=1;i<=8;i++)  { print pre"t"i, pre"b"i; print pre"t"i, pre"b"(i%8+1); }
  }' | tr ' ' '\t'; }
biggest() { stats "$@" | cut -d' ' -f2; }
# distinct_members FILE: fails if any cluster lists a node twice or its node count disagrees with its member list
distinct_members() { awk '{n=0; delete seen; for(i=1;i<=NF;i++) if($i=="{") break; for(++i;i<NF;i++) if(!seen[$i]++) ++n;
	if(n!=$1) bad=1} END{exit bad}' "$@"; }

gen_twocore "" > $TMP/twocore.el; make_samples twocore || fail "could not sample twocore"

# test_region_joins_cores: BLANT's own samples already link the two cores, so show the BFS only core A by removing
# every sample line and neighbor that mentions anything else. The BFS then builds exactly A; filling adds satellites
# until it is stuck at 18 nodes; core B can be reached only by a region round, which gives the satellites up for it.
# (The satellites must come from filling, not from the BFS: refinement never removes what the BFS found.)
mkdir -p $TMP/blind && cp $TMP/twocore.el $TMP/blind.el
awk '$1~/^a/{out=$1" "$2" "$3"\t"; for(i=4;i<=NF;i++) if($i~/^a/) out=out" "$i; print out}' $TMP/twocore/blant4.out > $TMP/blind/blant4.out
run_on blind "-m 5 -X 20" 0.5 > $TMP/blind.out || fail "two-core: script exited non-zero"
bigX=`biggest $TMP/blind.out`
[ "$bigX" -ge 20 ] || fail "two-core: biggest cluster is $bigX nodes with -X 20, expected at least 20 (both cores)"
[ "`run_on blind "-m 5 -X 0" 0.5 | biggest -`" -eq 12 ] || fail "two-core: with -X 0 the BFS should find exactly core A (12 nodes)"
BLANT_CLUSTERS_CHECK=1 run_on blind "-m 5 -X 20" 0.5 >/dev/null || fail "invariant check failed on blind twocore: `tail -2 $TMP/stderr`"
# test_default_is_fill_only: without -X the community is filled but no region round runs, so core A stops at 18 nodes
[ "`run_on blind "-m 5" 0.5 | biggest -`" -eq 18 ] || fail "two-core: default (fill only) should stop at 18 nodes, got `run_on blind "-m 5" 0.5 | biggest -`"
run_clusters_stderr "-v" 0.5 | grep -q "CORE refinement: .* 0 region rounds" || fail "default ran region rounds: `grep 'CORE refinement' -A1 $TMP/stderr | tr '\n' ' '`"
run_clusters_stderr "-v -X 20" 0.5 | grep "CORE refinement" -A1 | tr '\n' ' ' | grep -q " [1-9][0-9]* region rounds" || fail "-X 20 ran no region rounds"

# test_invariants (rejected rounds restore S exactly; counts stay true): check mode on CElegans and twocore
for x in "" "-X 20"; do
    BLANT_CLUSTERS_CHECK=1 run_clusters "$x" 0.5   >/dev/null || fail "invariant check failed at 0.5 with '$x': `tail -2 $TMP/stderr`"
    BLANT_CLUSTERS_CHECK=1 run_clusters "$x" 0.125 >/dev/null || fail "invariant check failed at 0.125 with '$x': `tail -2 $TMP/stderr`"
done
BLANT_CLUSTERS_CHECK=1 run_on twocore "-m 5" 0.5 >/dev/null || fail "invariant check failed on twocore: `tail -2 $TMP/stderr`"
# the check must be able to fail: BLANT_CLUSTERS_CHECK=selftest makes it assert a false statement
BLANT_CLUSTERS_CHECK=selftest run_on twocore "-m 5" 0.5 >/dev/null 2>&1 && fail "check mode cannot fail"

# test_max_size: -M 15 caps every cluster at 15
bigM=`run_clusters "-M 15" 0.125 | biggest -`
[ "$bigM" -le 15 ] && [ "$bigM" -ge 1 ] || fail "-M 15 exceeded or no clusters: biggest $bigM"

# test_weighted: weights 0.6/0.8/1.0 by line number; weighted edge sums must stay true through refinement
awk '{printf "%s\t%s\t%g\n", $1, $2, 0.6+0.2*(NR%3)}' networks/CElegans.el > $TMP/cw.elw
make_samples cw -w || fail "could not sample weighted network"
BLANT_CLUSTERS_CHECK=1 run_on cw "-w -X 20" 0.5 > $TMP/cw.out || fail "weighted invariant check failed: `tail -2 $TMP/stderr`"
[ -s $TMP/cw.out ] || fail "weighted run produced no clusters"

# test_tiny: two disjoint 5-cliques have no outside neighbors at all; refinement must stop cleanly and change nothing
awk 'BEGIN{for(i=1;i<=5;i++)for(j=i+1;j<=5;j++){print "c"i"\tc"j; print "d"i"\td"j}}' > $TMP/tiny.el
make_samples tiny || fail "could not sample tiny network"
BLANT_CLUSTERS_CHECK=1 run_on tiny "-m 2 -X 20" 1 > $TMP/tiny.out || fail "tiny: script exited non-zero: `tail -2 $TMP/stderr`"
[ "`stats $TMP/tiny.out | cut -d' ' -f1,2`" = "2 5" ] || fail "tiny: expected two 5-node clusters, got `stats $TMP/tiny.out`"

# test_long_ids: 18-digit node IDs sharing a 15-digit prefix (as in FlyWire) must stay distinct nodes
gen_twocore "" | awk '{for(i=1;i<=2;i++) if(!($i in id)) id[$i]=sprintf("720575940621287%03d", ++n); print id[$1]"\t"id[$2]}' > $TMP/longid.el
make_samples longid || fail "could not sample long-id network"
BLANT_CLUSTERS_CHECK=1 run_on longid "-m 5 -X 20" 0.5 > $TMP/longid.out || fail "long ids: script exited non-zero: `tail -2 $TMP/stderr`"
distinct_members $TMP/longid.out || fail "long ids: a cluster lists a node twice or miscounts its members"
[ "`biggest $TMP/longid.out`" -ge 20 ] || fail "long ids: biggest cluster `biggest $TMP/longid.out`, expected at least 20"

# test_skip_covered: a community that already lies mostly (more than the -o fraction) inside one refined earlier is
# not refined again (the overlap filter would discard it anyway); -v reports how often that happened
line=`run_clusters_stderr "-v" 0.125 | grep "CORE refinement: [0-9]* refined, [0-9]* skipped"`
[ -n "$line" ] || fail "no refinement counters with -v"
skipped=`echo "$line" | sed 's/.*refined, \([0-9]*\) skipped.*/\1/'`
[ "${skipped:-0}" -gt 0 ] || fail "no covered community was skipped at ED 0.125: $line"
# with -o 1 nothing can be more than 100% covered, so nothing is skipped
run_clusters_stderr "-v -o 1" 0.125 | grep -q "CORE refinement: [0-9]* refined, 0 skipped" || fail "-o 1 still skipped communities"

# test_growth_cap: a community may at most double (check mode asserts it per community, in the runs above), and one
# that grows into a community refined earlier is put back as the BFS found it; -v reports how many
run_clusters_stderr "-v" 0.125 | grep -q "CORE refinement: .* [0-9]* reverted" || fail "no reverted counter with -v"

# test_weighted_not_lost: refinement ignores weights, so it can dilute a community below the -emt edge-mean threshold.
# A community that passed the threshold as the BFS found it must not be lost that way (check mode asserts it).
# Weights 0.2/0.55/0.9 straddle the default threshold of 0.5.
awk '{printf "%s\t%s\t%g\n", $1, $2, (NR%3==0?0.2:NR%3==1?0.55:0.9)}' networks/CElegans.el > $TMP/cw2.elw
make_samples cw2 -w || fail "could not sample second weighted network"
for ed in 0.5 0.25; do
    BLANT_CLUSTERS_CHECK=1 run_on cw2 "-w" $ed >/dev/null || fail "weighted (straddling -emt) check failed at ED $ed: `tail -2 $TMP/stderr`"
done

# test_undo: with the estimate switched off every region is really added and trimmed, so most rounds fail and are
# undone; check mode then verifies that S, the edge count and the weight came back exactly. -v reports the undos.
for ed in 0.5 0.125; do
    BLANT_CLUSTERS_NOESTIMATE=1 BLANT_CLUSTERS_CHECK=1 run_clusters "-v -X 20" $ed >/dev/null || fail "check failed with undo forced at ED $ed: `tail -2 $TMP/stderr`"
    undone=`grep "CORE refinement" -A2 $TMP/stderr | tr '\n' ' ' | sed -n 's/.* \([0-9][0-9]*\) rounds undone.*/\1/p'`
    [ "${undone:-0}" -gt 20 ] || fail "ED $ed: expected many undone rounds with the estimate off, got '${undone}'"
done
BLANT_CLUSTERS_NOESTIMATE=1 BLANT_CLUSTERS_CHECK=1 run_on cw2 "-w -X 20" 0.5 >/dev/null || fail "weighted check failed with undo forced: `tail -2 $TMP/stderr`"

echo 'Done testing blant-clusters -X'
exit $exitCode
